#!/usr/bin/env python
"""Result tables for main.tex, written as LaTeX fragments under paper/tables from the raw CSVs.

Usage:  python make_tables.py
"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(HERE, "raw")
OUT = os.path.join(os.path.dirname(HERE), "tables")
os.makedirs(OUT, exist_ok=True)


def rows(name):
    with open(os.path.join(RAW, name), newline="") as fh:
        out = []
        for r in csv.DictReader(fh):
            d = {}
            for k, v in r.items():
                try:
                    d[k] = float(v) if ("." in v or "e" in v.lower()) else int(v)
                except (ValueError, AttributeError):
                    d[k] = v
            out.append(d)
        return out


def write(name, lines):
    with open(os.path.join(OUT, name), "w") as fh:
        fh.write("% generated by experiments/make_tables.py; do not edit\n" + "\n".join(lines) + "\n")


# experiment 1 ------------------------------------------------------------------------------
e1 = rows("exp1_summary.csv")
L = [r"\begin{tabular}{llccccc}", r"\toprule",
     r"& Demand & \multicolumn{3}{c}{Mean delay per vehicle (s)} & \multicolumn{2}{c}{Reduction (\%)} \\",
     r"\cmidrule(lr){3-5}\cmidrule(lr){6-7}",
     r"Profile & (veh/h) & Equal & Webster & RELAY & vs equal & vs Webster \\", r"\midrule"]
last = None
for r in e1:
    name = r["profile"].capitalize() if r["profile"] != last else ""
    if r["profile"] != last and last is not None:
        L.append(r"\midrule")
    last = r["profile"]
    L.append(f"{name} & {r['total_demand_vph']:.0f} & {r['fixed_equal_mean_wait_mean']:.1f} ({r['fixed_equal_mean_wait_sd']:.1f}) & "
             f"{r['fixed_webster_mean_wait_mean']:.1f} ({r['fixed_webster_mean_wait_sd']:.1f}) & {r['relay_mean_wait_mean']:.1f} ({r['relay_mean_wait_sd']:.1f}) & "
             f"${r['red_vs_fixed_equal_mean']:+.1f}$ ({r['red_vs_fixed_equal_sd']:.1f}) & ${r['red_vs_fixed_webster_mean']:+.1f}$ ({r['red_vs_fixed_webster_sd']:.1f}) \\\\")
L += [r"\bottomrule", r"\end{tabular}"]
write("exp1.tex", L)

# experiment 2 ------------------------------------------------------------------------------
e2 = rows("exp2_summary.csv")
names = {"fixed_webster": "Webster, independent", "fixed_coord": "Webster, coordinated",
         "relay_isolated": "RELAY, no coupling", "relay_coupled": "RELAY, coupled"}
L = [r"\begin{tabular}{llcccc}", r"\toprule",
     r"Demand & & Mean delay & Through & Stops per & Emergency \\",
     r"(veh/h) & Policy & per vehicle (s) & travel (s) & vehicle & traversal (s) \\", r"\midrule"]
for i, r in enumerate(e2):
    if i:
        L.append(r"\midrule")
    for j, (p, nm) in enumerate(names.items()):
        dem = f"{r['entering_vph']:.0f}" if j == 0 else ""
        amb = r.get(f"{p}_amb_corridor_mean", "")
        amb_sd = r.get(f"{p}_amb_corridor_sd", "")
        amb_s = f"{amb:.1f} ({amb_sd:.1f})" if isinstance(amb, float) and isinstance(amb_sd, float) else (f"{amb:.1f}" if isinstance(amb, float) else "")
        L.append(f"{dem} & {nm} & {r[f'{p}_mean_delay_mean']:.1f} ({r[f'{p}_mean_delay_sd']:.1f}) & "
                 f"{r[f'{p}_mean_through_travel_mean']:.1f} ({r[f'{p}_mean_through_travel_sd']:.1f}) & {r[f'{p}_mean_stops_mean']:.2f} & {amb_s} \\\\")
L += [r"\bottomrule", r"\end{tabular}"]
write("exp2.tex", L)

# experiment 3 ------------------------------------------------------------------------------
e3 = [r for r in rows("exp3_summary.csv") if r["level"] != "all"]
L = [r"\begin{tabular}{lcccccc}", r"\toprule",
     r"Demand & Policy & Mean & SD & Median & 95th pct & Worst \\", r"\midrule"]
labels = {"light": "Light ($m{=}0.6$)", "medium": "Medium ($m{=}1.0$)", "heavy": "Heavy ($m{=}1.4$)"}
allr = rows("exp3_preemption.csv")
for r in e3:
    L.append(f"{labels.get(r['level'], r['level'])} & RELAY & {r['relay_mean']:.2f} & {r['relay_sd']:.2f} & {r['relay_p50']:.2f} & {r['relay_p95']:.2f} & {r['relay_max']:.2f} \\\\")
lat_r = sorted(x["latency_relay"] for x in allr if isinstance(x.get("latency_relay"), (int, float)))
lat_f = sorted(x["latency_fixed"] for x in allr if isinstance(x.get("latency_fixed"), (int, float)))
import statistics
q = lambda xs, p: xs[min(len(xs) - 1, round(p * (len(xs) - 1)))]
for nm, xs in (("RELAY", lat_r), ("Equal split", lat_f)):
    L.append(f"All & {nm} & {statistics.fmean(xs):.2f} & {statistics.pstdev(xs):.2f} & {q(xs, .5):.2f} & {q(xs, .95):.2f} & {max(xs):.2f} \\\\")
L += [r"\bottomrule", r"\end{tabular}"]
write("exp3.tex", L)

# experiment 6b -----------------------------------------------------------------------------
e6b = rows("exp6b_biased_counts.csv")
labels6b = {"saturating_q8": r"Saturating, $q_{1/2}=8$", "saturating_q4": r"Saturating, $q_{1/2}=4$",
            "scale_0.8": "Scale 0.8", "scale_0.6": "Scale 0.6", "scale_0.4": "Scale 0.4 (lone vehicle rounds to 0)",
            "scale_0.4_keep1": "Scale 0.4, presence floor 1",
            "floor_0.8": "Scale 0.8, lone vehicle reads 0", "floor_0.6": "Scale 0.6, lone vehicle reads 0",
            "floor_0.8_keep1": "Scale 0.8, presence floor 1", "floor_0.6_keep1": "Scale 0.6, presence floor 1"}
L = [r"\begin{tabular}{lccc}", r"\toprule", r"Count model & Won & Worst (\%) & Mean (\%) \\", r"\midrule"]
models6b = [r["model"] for r in e6b]
missing = [m for m in dict.fromkeys(models6b) if m not in labels6b]
if missing:
    raise SystemExit(f"exp6b models without a table label: {missing}")
for model in labels6b:
    sub = [r for r in e6b if r["model"] == model]
    wins = sum(1 for r in sub if min(r["red_vs_fixed_equal"], r["red_vs_fixed_webster"]) > 0)
    worst = min(r["red_vs_fixed_webster"] for r in sub)
    mean = statistics.fmean(r["red_vs_fixed_webster"] for r in sub)
    L.append(f"{labels6b[model]} & {wins}/{len(sub)} & ${worst:+.1f}$ & ${mean:+.1f}$ \\\\")
L += [r"\bottomrule", r"\end{tabular}"]
write("exp6b.tex", L)

